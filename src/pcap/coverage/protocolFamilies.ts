export function isUnsupportedProtocolId(id: string): boolean {
  return id.startsWith('unsupported:')
}

export function unsupportedProtocolName(id: string): string | null {
  if (!isUnsupportedProtocolId(id)) return null
  const name = id.slice('unsupported:'.length)
  return name.length > 0 ? name : null
}

/**
 * Resolve family for a coverage / analysis protocol id.
 * Identified unsupported payloads (`unsupported:<name>`) get their own row id as familyId
 * under the identified-unsupported umbrella via labelKey.
 */
export function familyForProtocol(id: string): ProtocolFamilyRef {
  const key = id.toLowerCase()

  if (isUnsupportedProtocolId(key)) {
    const name = unsupportedProtocolName(key) ?? 'unknown'
    return {
      familyId: 'identified-unsupported',
      labelKey: `unsupported:${name}`,
      probable: true,
    }
  }

  const exact = EXACT[key]
  if (exact) {
    return { familyId: exact, labelKey: exact, probable: false }
  }

  // Longest prefix wins
  let best: { prefix: string; familyId: ProtocolFamilyId } | null = null
  for (const rule of PREFIX_RULES) {
    if (key.startsWith(rule.prefix)) {
      if (!best || rule.prefix.length > best.prefix.length) best = rule
    }
  }
  if (best) {
    return { familyId: best.familyId, labelKey: best.familyId, probable: false }
  }

  return { familyId: 'other', labelKey: 'other', probable: false }
}

/** Czech display label for a family ref (coverage / T10 panel). */
export function protocolFamilyLabel(ref: ProtocolFamilyRef): string {
  const families = cs.pcap.protocolFamilies
  if (ref.labelKey.startsWith('unsupported:')) {
    const name = ref.labelKey.slice('unsupported:'.length)
    return families.unsupportedNamed(name)
  }
  const direct = (families as Record<string, string | ((n: string) => string)>)[ref.labelKey]
  if (typeof direct === 'string') return direct
  return families.other
}

/** True when the id is accepted as a bare display-filter protocol token. */
export function isFilterableProtocolToken(id: string): boolean {
  const key = id.toLowerCase()
  if (key.length === 0) return false
  if (isUnsupportedProtocolId(key)) {
    return /^unsupported:[a-z][a-z0-9_-]*$/.test(key)
  }
  if (/^(ether|llc)-0x[0-9a-f]+$/.test(key)) return true
  if (/^(ipproto|proto)-\d+$/.test(key)) return true
  if (/^ipv6-(routing|opt)-\d+$/.test(key)) return true
  return familyForProtocol(key).familyId !== 'other' || key in EXACT
}
